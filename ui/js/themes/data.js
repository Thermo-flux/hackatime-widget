// Theme definitions. `tokens: null` means "use the stylesheet defaults" (follows the OS light/dark setting).
// Sprites are 16x16 grids ('.' = transparent) coloured through `legend`; `patches` are [x, y, char] overrides
// for expressions (all faces share one layout: eyes 2x2 at x=5-6 and x=9-10, mouth x=7-8, cheeks x=4 and x=11);
// `lines` are speech-bubble texts per mood (see mascot.js for the mood names).

/** "x,y=c x,y=c" -> [[x, y, "c"], ...] */
const P = (s) => s.split(" ").map((c) => { const [xy, ch] = c.split("="); const [x, y] = xy.split(",").map(Number); return [x, y, ch]; });
/** "a=#hex b=#hex" -> { a: "#hex", b: "#hex" } */
const L = (s) => Object.fromEntries(s.split(" ").map((p) => p.split("=")));
/** "line one|line two" -> ["line one", "line two"] (speech lines; keep each under ~30 characters). */
const S = (s) => s.split("|");

/** Colours every sprite theme gets for effects: X = heart red, Y = sparkle gold. A theme's legend may override them. */
const FX_LEGEND = { X: "#ff4d6d", Y: "#ffb81c" };

// Generated expression patches. Each face is described by `face`:
//   ey = top row of the 2x2 eyes (x 5-6 and 9-10), my = mouth row (x 7-8; cheeks sit at x 4 and 11 on that row),
//   s = skin, k = eye ink, m = mouth ink (default k), h = eye highlight, c = blush, mark = colour of ! and ?,
//   fx = [x, y] top-left of a small box (3 wide, up to 5 tall) for floating symbols.
// Templates: E = left eye area x 4-6, rows ey-1..ey+1 (mirrored onto x 9-11 unless R is given),
// M = mouth area x 6-9, rows my..my+1, F = symbol box. In templates '.' keeps the sprite pixel,
// k/m/s/h/c map to the face's chars, '!' maps to `mark`, anything else (X, Y) is used as is.
const FACE_EXPR = {
  surprised: { E: [".kh", ".kk", ".kk"], R: ["kh.", "kk.", "kk."], M: [".ss.", ".mm."], F: [".!.", ".!.", ".!.", "...", ".!."] },
  love: { E: ["X.X", "XXX", ".Xs"], M: ["mssm", ".mm."], F: ["X.X", "XXX", ".X."] },
  wink: { E: ["...", ".kh", ".kk"], R: ["...", "sks", "ksk"], M: ["mssm", ".mm."] },
  excited: { E: ["...", ".ks", "ksk"], M: ["mmmm", ".XX."], F: [".Y.", "YYY", ".Y."] },
  grumpy: { E: ["kk.", "ssk", ".kk"], M: [".mm.", "m..m"], C: "s" },
  thinking: { E: ["...", ".sk", ".sk"], R: ["...", "sk.", "sk."], M: ["ssmm", "...."], F: ["!!.", "..!", ".!.", "...", ".!."] },
  proud: { E: ["...", "kkk", "skk"], M: ["mssm", ".mm."], extra: (f) => [[7, f.ey, f.k], [8, f.ey, f.k], [5, f.ey, f.h], [10, f.ey, f.h]] },
  dizzy: { E: ["k.k", "sks", "ksk"], M: ["ssss", ".mm."], C: "s", F: ["Y.Y", ".Y.", "Y.Y"] },
};

function facePatches(f) {
  const map = (ch) => ({ k: f.k, m: f.m ?? f.k, s: f.s, h: f.h, c: f.c, "!": f.mark ?? "Y" })[ch] ?? ch;
  const stamp = (out, rows, x0, y0, mirror = false) => rows.forEach((row, dy) => [...row].forEach((ch, dx) => {
    if (ch !== ".") out.push([mirror ? 15 - (x0 + dx) : x0 + dx, y0 + dy, map(ch)]);
  }));
  const patches = {};
  for (const [name, e] of Object.entries(FACE_EXPR)) {
    const out = [];
    stamp(out, e.E, 4, f.ey - 1);
    if (e.R) stamp(out, e.R, 9, f.ey - 1); else stamp(out, e.E, 4, f.ey - 1, true);
    stamp(out, e.M, 6, f.my);
    if (e.C) out.push([4, f.my, map(e.C)], [11, f.my, map(e.C)]);
    if (e.F) stamp(out, e.F, f.fx[0], f.fx[1]);
    if (e.extra) out.push(...e.extra(f));
    patches[name] = out.filter(([x, y]) => x >= 0 && x < 16 && y >= 0 && y < 16);
  }
  return patches;
}

